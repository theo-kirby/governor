// STATE.md and the orientation brief, both from one snapshot.
import { parseEdge, section } from "./model";
import { live, tail, type GraphSnapshot, type GNode } from "./snapshot";

const FRONTIER = ["broken", "blocked", "open"] as const;

function cites(s: GraphSnapshot, n: GNode): GNode[] {
  return s.edges
    .filter((e) => e.source === n.id && s.nodes[e.target]?.kind === "record")
    .map((e) => s.nodes[e.target])
    .sort((a, b) => b.seq - a.seq);
}
const label = (n: GNode) => n.slug || n.id.slice(0, 8);
const firstLine = (text: string, max = 200) => {
  const line = text.split("\n").map((l) => l.replace(/^[-*]\s*/, "").trim()).find((l) => l && !l.startsWith("_(")) ?? "";
  return line.length > max ? line.slice(0, max - 1) + "…" : line;
};

export function renderState(s: GraphSnapshot, opts: { title?: string } = {}): string {
  const root = s.root ? s.nodes[s.root] : null;
  const claims = live(s).filter((n) => n.kind === "state");
  const lines: string[] = [
    `# ${opts.title ?? root?.title ?? "State"}`,
    "",
    "Generated by `governor render` from the Flywheel graph — do not edit by hand.",
    `Head: \`${s.head ?? "none"}\`.`,
    "",
    "## Frontier",
    "",
  ];
  const frontier = claims.filter((n) => (FRONTIER as readonly string[]).includes(n.status ?? ""));
  if (!frontier.length) lines.push("_Nothing open, broken or blocked._");
  for (const st of FRONTIER)
    for (const n of frontier.filter((n) => n.status === st))
      lines.push(`- **[${st}]** ${n.title} (\`${label(n)}\`) — ${firstLine(section(n.content, "Current"))}`);
  const t = tail(s);
  lines.push("", `## Unfolded records (${t.length})`, "");
  if (!t.length) lines.push("_None: state is current._");
  for (const r of t.slice(-20)) lines.push(`- \`${label(r)}\` ${r.title}`);
  if (t.length > 20) lines.push(`- … and ${t.length - 20} more`);
  lines.push("", "## Architecture", "");
  const walk = (id: string, depth: number) => {
    const kids = (s.nodes[id]?.children ?? [])
      .map((c) => s.nodes[c])
      .filter((n) => n?.live && n.kind === "state")
      .sort((a, b) => (a.title < b.title ? -1 : 1));
    for (const n of kids) {
      if (n.status === "superseded") continue;
      const c = cites(s, n);
      const status = n.status ? `[${n.status}] ` : "";
      lines.push(`${"  ".repeat(depth)}- ${status}**${n.title}** (\`${label(n)}\`) — ${firstLine(section(n.content, "Current"), 160)}${c.length ? ` [${c.length} record(s)]` : ""}`);
      walk(n.id, depth + 1);
    }
  };
  if (s.root) walk(s.root, 0);
  const superseded = claims.filter((n) => n.status === "superseded");
  if (superseded.length) lines.push("", `_${superseded.length} superseded claim(s) omitted._`);
  return lines.join("\n") + "\n";
}

export function orient(s: GraphSnapshot, opts: { recent?: number } = {}): string {
  const out = [renderState(s)];
  const t = tail(s);
  if (t.length) {
    out.push("## The tail's declared impacts", "");
    for (const r of t) {
      out.push(`- \`${label(r)}\` ${r.title}`);
      for (const e of s.edges.filter((e) => e.source === r.id)) {
        const p = parseEdge(e.content);
        if (p.relation === "impact") for (const l of p.lines) out.push(`  - → \`${label(s.nodes[e.target])}\`: ${l.text}`);
      }
      for (const m of r.content.matchAll(/^- NEW ([a-z0-9-]+) — (.*)$/gm)) out.push(`  - → NEW ${m[1]}: ${m[2]}`);
      if (/^none:/m.test(r.content.split(/^## State Impact\s*$/m)[1] ?? "")) out.push("  - none");
    }
    out.push("");
  }
  const recent = live(s).filter((n) => n.kind === "record").sort((a, b) => b.seq - a.seq).slice(0, opts.recent ?? 8);
  out.push("## Most recent records", "", ...recent.map((r) => `- \`${label(r)}\` ${r.title}${r.at ? ` (${r.at.slice(0, 10)})` : ""}`), "");
  return out.join("\n");
}
